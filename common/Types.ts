/**
 * Common types shared between UI and Web workers.
 *
 * These describe plain data as it crosses the postMessage boundary:
 * structured cloning strips class identity, so a THREE.Vector3 sent by the
 * UI arrives in the worker as a plain `{x, y, z}` object (and vice versa).
 */

export interface PlainVector2 {
  x: number;
  y: number;
}

/**
 * A plain {x, y, z} vector. Values sent across the worker boundary are
 * structured-cloned, so a THREE.Vector3 arrives as a plain object without
 * Vector3 class identity (no `isVector3`, no methods). Code on the receiving
 * end must treat these as data, not as Vector3 instances.
 */
export interface PlainVector3 {
  x: number;
  y: number;
  z: number;
}

/**
 * These values are deltas generated by the UI. Values of 0 mean nothing is changing and the player is still
 */
export interface Movement {
  move: PlainVector3;
  turn: PlainVector2;
}

export interface AddBlockArgs {
  position: PlainVector3;
  side: number;
  type: number;
}

export interface SetBlocksArgs {
  start: PlainVector3;
  end: PlainVector3;
  type: number;
  colour: number;
  update: boolean;
}

export interface PlayerPositionChangeArgs {
  position: PlainVector3;
  target: PlainVector3;
}

export interface PlayerPositionChangeListener {
  (args: PlayerPositionChangeArgs): void;
}

export interface BoundScriptsChangeArgs {
  scripts: BoundScripts;
}

export interface BoundScriptsChangeListener {
  (args: BoundScriptsChangeArgs): void;
}

export type BoundScripts = number[];
